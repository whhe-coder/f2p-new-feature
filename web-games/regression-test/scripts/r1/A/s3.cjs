const {run, BASE, settle, track, pick, now, waitFor, clientNav, fiberFind, path, remotes} = require(__dirname + '/../A/h.cjs');
run(async (page) => {
  const tr = track(page);
  const out = {};
  out.t1 = now();
  await page.goto(`${BASE}/53105/communication-hub`, {waitUntil: 'domcontentloaded'});
  out.u1 = path(await settle(page));
  await page.waitForTimeout(12000);
  out.hub = await fiberFind(page, ['accountId', 'merchantId', 'locale'], 2);
  out.hubReqs = pick(tr.gw, /mf-manifest|remoteEntry|chat\.nl-k8s/).slice(0, 12);
  out.mfwarn = tr.errs.filter(e => /mf-runtime|warn/i.test(e));
  out.consoleAll = [];
  page.on('console', m => { if (/mf-runtime/.test(m.text())) out.consoleAll.push(m.type() + ':' + m.text().slice(0, 200)); });
  out.t2 = now();
  await clientNav(page, '/for/web-games/account/53105/support-hub');
  out.u2 = path(await settle(page));
  out.t3 = now();
  await clientNav(page, '/for/web-games/account/53105/analytics/products/site-builder?from=2026-01-01');
  out.u3 = path(await settle(page));
  await page.waitForTimeout(4000);
  out.xaa3 = (await remotes(page)).filter(r => r.name === 'xaa_widgets').map(r => r.props.componentName);
  out.t4 = now();
  await clientNav(page, '/for/web-games/account/53105/analytics/main-info/afs/chargeback-registry');
  out.u4 = path(await settle(page));
  await page.waitForTimeout(9000);
  out.cb = (await remotes(page)).map(r => ({name: r.name, exposedModule: r.exposedModule, props: r.props, childMounted: r.childMounted, child: r.child}));
  out.reqs = pick(tr.gw, /remoteEntry|mf-manifest|disputes|chargeback/);
  out.errs = tr.errs.filter(e => !/BLOCKED_BY_CLIENT/.test(e)).slice(0, 10);
  return out;
});
