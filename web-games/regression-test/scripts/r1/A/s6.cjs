const {run, BASE, settle, track, pick, now, waitFor, clientNav, remotes, path} = require(__dirname + '/../A/h.cjs');
const M = '/for/web-games/account/53105';
const brief = r => Array.isArray(r) ? r.map(x => ({name: x.name, exposedModule: x.exposedModule, props: x.props, childMounted: x.childMounted})) : r;
run(async (page) => {
  const tr = track(page);
  const out = {t1: now()};
  await page.goto(`${BASE}/53105/support`, {waitUntil: 'domcontentloaded', timeout: 60000});
  out.u1 = path(await settle(page));
  await waitFor(page, () => !!window.transactions_publisher_account, 40000);
  await page.waitForTimeout(5000);
  out.support = brief(await remotes(page));
  out.t2 = now();
  await clientNav(page, M + '/support/subscriptions');
  await waitFor(page, () => !!window.subscriptions_publisher_account, 25000);
  await page.waitForTimeout(5000);
  out.u2 = path(page.url());
  out.subs = brief(await remotes(page));
  out.subsWin = await page.evaluate(() => typeof window.subscriptions_publisher_account);
  out.t3 = now();
  await clientNav(page, M + '/finance');
  out.u3 = path(await settle(page));
  await page.waitForTimeout(6000);
  out.fin0 = brief(await remotes(page));
  out.tabs = await page.evaluate(() => [...document.querySelectorAll('[role=tab]')].map(e => `${e.textContent.trim()}|${e.getAttribute('aria-selected')}`));
  // mark first remote DOM node to detect remount
  const tag = async () => page.evaluate(() => { const n = document.querySelectorAll('[data-a-mark]').length; return n; });
  await page.evaluate(() => { const hasRoot = el => Object.keys(el).some(k => k.startsWith('__reactContainer')); const rootEl=[document.getElementById('root'),...document.querySelectorAll('body > *')].find(el=>el&&hasRoot(el)); const st=[rootEl[Object.keys(rootEl).find(k=>k.startsWith('__reactContainer'))]]; let n=0; while(st.length&&n++<300000){const f=st.pop(); if(!f) continue; const p=f.memoizedProps; if(p&&p.name==='finance'&&typeof f.type==='function'){let c=f.child; while(c&&!(c.stateNode instanceof Element)) c=c.child; if(c) c.stateNode.setAttribute('data-a-mark','1'); break;} if(f.sibling) st.push(f.sibling); if(f.child) st.push(f.child);} });
  out.markBefore = await tag();
  const payTab = page.locator('[role=tab]', {hasText: /Payouts/}).first();
  await payTab.click({timeout: 5000}).catch(e => out.clickErr = 'payouts click failed');
  await page.waitForTimeout(6000);
  out.u3b = path(page.url());
  out.fin1 = brief(await remotes(page));
  out.hidden = await page.evaluate(() => { const m = document.querySelector('[data-a-mark]'); if (!m) return 'mark gone'; let e = m; while (e && e !== document.body) { const cs = getComputedStyle(e); if (cs.display === 'none' || e.hidden) return `hidden at ${e.tagName}.${e.className}`.slice(0, 120); e = e.parentElement; } return 'visible'; });
  const regTab = page.locator('[role=tab]').first();
  await regTab.click({timeout: 5000}).catch(e => out.clickErr2 = 'tab0 click failed');
  await page.waitForTimeout(3000);
  out.u3c = path(page.url());
  out.markAfter = await tag();
  out.t4 = now();
  await clientNav(page, M + '/finance/reports');
  await page.waitForTimeout(8000);
  out.u4 = path(page.url());
  out.reports = brief(await remotes(page));
  out.reqs = pick(tr.gw, /remoteEntry|transactions_publisher_account|subscriptions-publisher|\.js\?v=/);
  out.errs = [...new Set(tr.errs.filter(e => !/BLOCKED_BY_CLIENT|status of 404|Datadog/.test(e)))].slice(0, 8);
  return out;
});
